// Copies the public docs (docs/site/*.md) to everything that ships them, so each image and
// package builds from its own folder: the web app (as a generated module), the open library
// (zeitwide.docs, offline) and the pipeline (llms-full.txt), plus the OpenAPI document the
// pipeline turns into the API reference. Tests in each fail when a copy is stale.
//   node scripts/sync-docs.mjs        (or `make sync-docs` from the repo root)
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const source = join(root, "docs", "site");
const files = readdirSync(source)
  .filter((name) => name.endsWith(".md"))
  .sort();

// web: one module, so pages and the Markdown route need no file system at run time.
const docs = Object.fromEntries(
  files.map((name) => [name.replace(/\.md$/, ""), readFileSync(join(source, name), "utf8")]),
);
writeFileSync(
  join(root, "web", "src", "content", "docs.generated.ts"),
  `// Generated by scripts/sync-docs.mjs from docs/site/*.md. Do not edit.\n\nexport const DOCS: Readonly<Record<string, string>> = ${JSON.stringify(docs, null, 2)};\n`,
);

for (const target of [
  join(root, "lib-python", "src", "zeitwide", "docs"),
  join(root, "pipeline", "src", "zeitwide_pipeline", "site", "docs"),
]) {
  mkdirSync(target, { recursive: true });
  for (const name of readdirSync(target).filter((n) => n.endsWith(".md"))) {
    rmSync(join(target, name));
  }
  for (const name of files) {
    copyFileSync(join(source, name), join(target, name));
  }
}

copyFileSync(
  join(root, "web", "src", "api", "openapi.json"),
  join(root, "pipeline", "src", "zeitwide_pipeline", "site", "openapi.json"),
);
console.warn(`Synced ${files.length} docs`);
